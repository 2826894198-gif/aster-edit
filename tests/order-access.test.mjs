import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
const origin = 'http://127.0.0.1:8088';
const api = `${origin}/wp-json/aster/v1/`;
const cli = mode => JSON.parse(execFileSync('docker', ['compose', 'run', '--rm', 'cli', 'eval-file', '/workspace/tests/http-fixture.php', mode], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim());
const post = (path, body, extra = {}) => fetch(api + path, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...extra }, body: JSON.stringify(body) });

test('real HTTP + SMTP: guest lookup, single-use exchange and privacy', async () => {
  const fixture = cli('reset');
  const since = new Date().getTime() - 2000;
  const direct = await post('order-access/lookup', fixture);
  assert.equal(direct.status, 200);
  assert.match(direct.headers.get('cache-control'), /no-store/);
  const directOrder = await direct.json();
  assert.equal(directOrder.order_number, fixture.order_number);
  assert.equal(directOrder.status, 'pending');
  assert.ok(!JSON.stringify(directOrder).includes(fixture.email));
  assert.equal((await post('order-access/lookup', { ...fixture, email: 'wrong@aster.test' })).status, 404);
  assert.equal((await fetch(api + 'order-access/order')).status, 401);
  assert.equal((await post('order-access-requests', fixture, { Origin: 'https://attacker.test' })).status, 403);
  const unknown = await post('order-access-requests', { ...fixture, email: 'wrong@aster.test' });
  const known = await post('order-access-requests', fixture);
  assert.equal(known.status, 202);
  assert.equal(unknown.status, 202);
  assert.deepEqual(await known.json(), await unknown.json());
  assert.match(known.headers.get('cache-control'), /no-store/);
  cli('drain');
  const inbox = await (await fetch('http://127.0.0.1:8028/api/v1/messages?limit=100')).json();
  const candidates = inbox.messages.filter(m => m.Subject === 'Aster Edit — your order access link' && new Date(m.Created).getTime() >= since && m.To.some(a => a.Address === fixture.email));
  assert.ok(candidates.length, 'A matching access email actually arrived in Mailpit');
  const mail = await (await fetch(`http://127.0.0.1:8028/api/v1/message/${candidates[0].ID}`)).json();
  const token = mail.Text.match(/#access=([a-f0-9]{64})/)?.[1];
  assert.ok(token, 'Email contains a fragment-only access link');
  const page = await fetch(`${origin}/order-status/`);
  assert.equal(page.status, 200);
  assert.match(page.headers.get('content-security-policy'), /frame-ancestors 'none'/);
  assert.equal(page.headers.get('referrer-policy'), 'no-referrer');
  assert.ok(!inbox.messages.some(m => m.Subject === 'Aster Edit — your order access link' && new Date(m.Created).getTime() >= since && m.To.some(a => a.Address === 'wrong@aster.test')), 'No mail delivered for mismatched email');
  // Eight truly concurrent HTTP requests must result in exactly one successful exchange.
  const exchanges = await Promise.all(Array.from({ length: 8 }, () => post('order-access/exchange', { token })));
  assert.equal(exchanges.filter(r => r.status === 200).length, 1, 'Concurrent consumption has exactly one winner');
  assert.equal(exchanges.filter(r => r.status === 401).length, 7);
  const winner = exchanges.find(r => r.status === 200);
  const setCookie = winner.headers.get('set-cookie');
  assert.ok(setCookie.includes('HttpOnly') && setCookie.includes('SameSite=Strict') && setCookie.includes('Max-Age=900'));
  const cookie = setCookie.split(';')[0];
  const lookup = await fetch(api + 'order-access/order', { headers: { Cookie: cookie, Origin: 'https://attacker.test' } });
  assert.equal(lookup.headers.get('access-control-allow-origin'), null);
  assert.match(lookup.headers.get('cache-control'), /no-store/);
  assert.equal(lookup.status, 200);
  const order = await lookup.json();
  assert.equal(order.order_number, fixture.order_number);
  assert.equal(order.status, 'pending');
  assert.equal(order.items[0].quantity, 2);
  assert.deepEqual(Object.keys(order).sort(), ['created_at', 'currency', 'items', 'order_number', 'refunded_total', 'shipping_total', 'status', 'status_label', 'tax_total', 'total'].sort());
  assert.ok(!JSON.stringify(order).includes(fixture.email));
  assert.equal((await fetch(api + 'order-access/order?order_id=1', { headers: { Cookie: cookie } })).status, 400);
  assert.equal((await post('order-access/logout', {}, { Cookie: cookie })).status, 200);
  assert.equal((await fetch(api + 'order-access/order', { headers: { Cookie: cookie } })).status, 401);
  for (let i = 0; i < 5; i++) assert.equal((await post('order-access-requests', fixture)).status, 202);
  cli('drain');
  const after = await (await fetch('http://127.0.0.1:8028/api/v1/messages?limit=100')).json();
  const sent = after.messages.filter(m => m.Subject === 'Aster Edit — your order access link' && new Date(m.Created).getTime() >= since && m.To.some(a => a.Address === fixture.email));
  assert.equal(sent.length, 3, 'Per-order/email throttling suppresses excess emails with identical public responses');
});

test('draft launch catalog cannot leak through public Store API', async () => {
  const response = await fetch(`${origin}/wp-json/wc/store/v1/products?per_page=100`);
  assert.equal(response.status, 200);
  const products = await response.json();
  const draftIds = new Set(cli('catalog-ids'));
  assert.equal(draftIds.size, 38, 'Check the actual 38 draft launch records; later approved cups are separate');
  assert.equal(products.filter(p => draftIds.has(p.id)).length, 0);
});
